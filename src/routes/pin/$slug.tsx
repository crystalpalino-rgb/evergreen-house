import {
  createFileRoute,
  notFound,
  isNotFound,
  redirect,
} from "@tanstack/react-router";
import { Header } from "~/components/Header";
import { Footer } from "~/components/Footer";
import { Breadcrumbs } from "~/components/Breadcrumbs";
import { AnalyticsList } from "~/components/AnalyticsList";
import { AmazonDisclosure } from "~/components/AmazonDisclosure";
import { EditProductCard } from "~/components/EditProductCard";
import { PinUnavailableCard } from "~/components/PinUnavailableCard";
import { getCuratedProducts, getEdit, type EditProduct } from "~/lib/edits";
import { resolvePinSlug, type PinPage } from "~/lib/pins";
import { generateStaticMetadata, SITE_URL } from "~/lib/seo";

/**
 * Pinterest landing page: /pin/<slug> (project P3).
 *
 * The visitor tapped a pin, so this page opens with that pin's own art and then
 * answers it: the same numbered discs, in the same order, each opening onto the
 * product behind it. Copy and number order come from the checked-in pin manifest
 * (src/data/pins/manifest.json, generated by scripts/build-pin-pages.mjs); the
 * live product facts come from the products table by id.
 *
 * It is a top-level route, deliberately not nested under /collections/, so the
 * page has one canonical URL and does not inherit the edit page's.
 *
 * A number whose product has no Amazon buy box is rendered honestly rather than
 * removed (see src/components/PinUnavailableCard.tsx): the count on the page
 * always matches the count on the pin.
 */

type PinLoaderData = {
  pin: PinPage;
  products: EditProduct[];
};

export const Route = createFileRoute("/pin/$slug")({
  loader: async ({ params }): Promise<PinLoaderData> => {
    const resolution = resolvePinSlug(params.slug);
    /* A pin that was retired keeps its URL alive: Pinterest serves the old image
       for years, so the URL redirects permanently to the edit that answers it
       now. A slug that was never a pin is a real 404. */
    if (resolution.kind === "retired") {
      throw redirect({ href: resolution.destination, statusCode: 301 });
    }
    if (resolution.kind === "unknown") throw notFound();

    const pin = resolution.pin;
    try {
      const products = await getCuratedProducts(
        pin.numbers.map((n) => ({
          id: n.productId,
          slug: n.productSlug ?? "",
          display_title: n.displayTitle,
          hook: n.hook ?? "",
        })),
      );
      return { pin, products };
    } catch (err) {
      if (isNotFound(err)) throw err;
      /* Database down: the page still renders every number, with its label and
         its numeral, rather than an empty shell or a shorter list. */
      console.error("Pin page loader error:", err);
      return { pin, products: [] };
    }
  },
  head: ({ loaderData }) => {
    const pin = loaderData?.pin;
    if (!pin) return {};
    const seo = generateStaticMetadata(
      pin.title,
      pin.metaDescription,
      `/pin/${pin.slug}`,
      {
        image: `${SITE_URL}${pin.image}`,
        imageWidth: pin.imageWidth,
        imageHeight: pin.imageHeight,
      },
    );
    /* LCP: the pin art is the first paint element, so it is preloaded at its
       real 2:3 size. */
    const links = [
      ...seo.links,
      { rel: "preload", as: "image", href: pin.image, type: "image/jpeg" },
    ];
    return { meta: seo.meta, links };
  },
  component: PinLandingPage,
});

function PinLandingPage() {
  const { pin, products } = Route.useLoaderData();
  const url = `${SITE_URL}/pin/${pin.slug}`;
  const byId = new Map(products.map((product) => [product.id, product]));

  /* The edit behind the pin, so the CTA can name it rather than say "here". */
  const destinationSlug = pin.destination.replace(/^\/collections\//, "");
  const edit = getEdit(destinationSlug);
  const editTitle = edit?.title ?? "the full edit";

  /* The numbered cards, in pin order. The number is the manifest's, never the
     index, so a product that goes off sale keeps its number and its slot. */
  const cards = pin.numbers.map((number) => {
    const product = byId.get(number.productId) ?? null;
    return { number, product };
  });

  const onSale = cards.filter((card) => card.product && !card.number.unavailable);

  const schema = JSON.stringify({
    "@context": "https://schema.org",
    "@type": "ItemList",
    name: pin.title,
    description: pin.metaDescription,
    url,
    numberOfItems: pin.numbers.length,
    itemListElement: pin.numbers.map((number) => ({
      "@type": "ListItem",
      position: number.n,
      name: number.displayTitle,
      ...(number.unavailable || !number.productSlug
        ? {}
        : { url: `${SITE_URL}/product/${number.productSlug}` }),
    })),
  });

  return (
    <>
      <Header />
      <main>
        <Breadcrumbs items={[{ label: "Home", href: "/" }, { label: pin.title }]} />
        <script
          type="application/ld+json"
          dangerouslySetInnerHTML={{ __html: schema }}
        />

        {/* The pin itself, at its native 2:3, beside the copy: she should
            recognise the image she tapped before she reads a word. */}
        <section className="bg-soft-white pb-6 pt-4 sm:pb-10 sm:pt-6">
          <div className="mx-auto max-w-7xl px-4 sm:px-6 lg:px-8">
            <div className="grid gap-6 sm:gap-8 lg:grid-cols-[minmax(0,300px)_minmax(0,1fr)] lg:gap-12">
              <figure className="mx-auto w-full max-w-[300px] lg:mx-0">
                <img
                  src={pin.image}
                  alt={pin.alt}
                  width={pin.imageWidth}
                  height={pin.imageHeight}
                  fetchpriority="high"
                  loading="eager"
                  decoding="sync"
                  className="w-full rounded-2xl border border-beige/30 shadow-sm"
                />
                <figcaption className="mt-2 text-center text-[11px] text-taupe lg:text-left">
                  The pin you tapped.
                </figcaption>
              </figure>

              <div className="lg:pt-2">
                <p className="text-[0.7rem] font-semibold uppercase tracking-[0.28em] text-antique-gold">
                  From Pinterest
                </p>
                <h1 className="mt-2.5 max-w-[28rem] font-serif text-[1.75rem] font-semibold leading-[1.1] text-warm-dark sm:text-4xl">
                  {pin.title}
                </h1>
                <p className="mt-3 max-w-[34rem] font-serif text-lg leading-snug text-warm-dark sm:text-xl">
                  {pin.headline}
                </p>
                <p className="mt-3 max-w-[34rem] text-sm leading-relaxed text-warm-gray sm:text-base">
                  {pin.intro}
                </p>
                <p className="mt-5">
                  <a
                    href={pin.destination}
                    className="inline-flex min-h-11 items-center justify-center rounded-full bg-midnight px-5 py-2.5 text-[11px] font-semibold uppercase tracking-[0.12em] text-soft-white transition-colors duration-200 hover:bg-midnight-deep"
                  >
                    Shop {editTitle}
                  </a>
                </p>
              </div>
            </div>
          </div>
        </section>

        {/* The numbered pieces, in pin order, immediately below. */}
        <section className="bg-soft-white pb-10 pt-2 sm:pb-14 sm:pt-4">
          <div className="mx-auto max-w-7xl px-4 sm:px-6 lg:px-8">
            <div className="flex items-baseline justify-between gap-4 border-t border-beige/30 pt-5">
              <h2 className="font-serif text-xl text-warm-dark sm:text-2xl">
                The pieces on this pin
              </h2>
              <p className="text-xs uppercase tracking-[0.14em] text-taupe">
                {pin.numbers.length} pieces
              </p>
            </div>
            <AnalyticsList
              id={`pin:${pin.slug}`}
              name={pin.title}
              context={`pin:${pin.slug}`}
              items={onSale.map((card) => ({
                id: card.product!.id,
                name: card.product!.title,
              }))}
            >
              <div className="mt-4 grid grid-cols-2 gap-3 sm:mt-6 sm:grid-cols-3 sm:gap-5 lg:grid-cols-4">
                {cards.map(({ number, product }) =>
                  product && !number.unavailable ? (
                    <EditProductCard
                      key={number.n}
                      product={product}
                      number={number.n}
                    />
                  ) : (
                    <PinUnavailableCard
                      key={number.n}
                      number={number.n}
                      label={number.label}
                      displayTitle={number.displayTitle}
                      imageUrl={product?.imageUrl ?? null}
                      imageAlt={
                        product?.imageAlt ??
                        `${number.displayTitle} - Evergreen House`
                      }
                    />
                  ),
                )}
              </div>
            </AnalyticsList>
            <div className="mt-6">
              <AmazonDisclosure />
            </div>
          </div>
        </section>
      </main>
      <Footer />
    </>
  );
}
