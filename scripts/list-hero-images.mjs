#!/usr/bin/env node
/**
 * Write src/data/hero-images.json: every piece of site art in public/images,
 * as the base path the edit rows store (no extension) plus a label and a
 * thumbnail URL.
 *
 * The curation screens offer this list in a dropdown, so the owner picks the art
 * from what the site already has (owner decision 23, 2026-11-05: a dropdown of
 * existing heroes, no upload). The list is generated and checked in because the
 * deployed server cannot read public/images at request time.
 *
 * A base path is the file name without .jpg / .webp, which is exactly how
 * `hero_image` and `card_image` are stored and how src/lib/edits.ts
 * `artSources()` appends the two extensions. Both files must exist for an entry
 * to be offered, so the dropdown can never hand back art that only has one of
 * the two formats.
 *
 * Usage: bun run scripts/list-hero-images.mjs
 */
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const IMAGES = join(ROOT, "public", "images");
const OUT = join(ROOT, "src", "data", "hero-images.json");

const files = readdirSync(IMAGES);

/** base -> set of extensions present */
const byBase = new Map();
for (const file of files) {
  const match = /^(.+)\.(jpg|webp)$/.exec(file);
  if (!match) continue;
  const [, base, ext] = match;
  if (!byBase.has(base)) byBase.set(base, new Set());
  byBase.get(base).add(ext);
}

/** A readable label from the file name, e.g. edit-heritage-christmas-edit-hero-light. */
function label(base) {
  return base
    .replace(/^edit-/, "")
    .replace(/-/g, " ")
    .replace(/\b\w/g, (c) => c.toUpperCase());
}

const images = [...byBase.entries()]
  .filter(([, exts]) => exts.has("jpg") && exts.has("webp"))
  .map(([base]) => ({
    path: `/images/${base}`,
    thumb: `/images/${base}.jpg`,
    label: label(base),
    group: base.startsWith("edit-") ? "Collection art" : "Site art",
  }))
  .sort((a, b) => a.group.localeCompare(b.group) || a.path.localeCompare(b.path));

const payload = {
  note:
    "Generated by scripts/list-hero-images.mjs from public/images. Base paths only: src/lib/edits.ts artSources() appends .webp and .jpg. Do not edit by hand.",
  images,
};

writeFileSync(OUT, `${JSON.stringify(payload, null, 2)}\n`);
const jpgOnly = [...byBase.entries()].filter(([, exts]) => !(exts.has("jpg") && exts.has("webp"))).length;
console.log(`Wrote src/data/hero-images.json (${images.length} images, ${jpgOnly} skipped for missing a format)`);
