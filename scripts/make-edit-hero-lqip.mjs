/**
 * Build src/lib/edit-hero-lqip.ts: a tiny blurred placeholder for every Edit
 * page hero, inlined as a data URI.
 *
 * Why this exists: the Edit page hero band paints its art as an <img> over a
 * flat midnight panel. Until that image decodes (a 176 to 269 KB WebP on a cold
 * cache) the band is a blank dark box, which is what an audit pass captured.
 * With the placeholder inlined into the HTML, the band paints Crystal's photo
 * on the first frame and the full-resolution art covers it when it arrives.
 *
 * Run after any new hero art lands:  node scripts/make-edit-hero-lqip.mjs
 */
import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const IMAGES = path.resolve("public/images");
const OUT = path.resolve("src/lib/edit-hero-lqip.ts");
const HERO = /^edit-.*-hero-.*\.jpg$/;

const files = (await fs.readdir(IMAGES)).filter((name) => HERO.test(name)).sort();
if (files.length === 0) throw new Error("no edit hero art found in public/images");

const out = {};
for (const file of files) {
  const data = await sharp(path.join(IMAGES, file))
    .resize({ width: 24 })
    .blur(1.2)
    .jpeg({ quality: 42, chromaSubsampling: "4:2:0" })
    .toBuffer();
  const key = `/images/${file.replace(/\.jpg$/, "")}`;
  out[key] = `data:image/jpeg;base64,${data.toString("base64")}`;
  console.log(`${key}  ${data.length} bytes`);
}

const body = Object.entries(out)
  .map(([key, uri]) => `  "${key}": "${uri}",`)
  .join("\n");
await fs.writeFile(
  OUT,
  `/**\n * Generated by scripts/make-edit-hero-lqip.mjs. Do not edit by hand.\n *\n * A 24px blurred placeholder per Edit hero, inlined so the hero band paints\n * Crystal\x27s photo on the first frame instead of a blank dark panel.\n */\nexport const EDIT_HERO_LQIP: Record<string, string> = {\n${body}\n};\n`,
);
console.log(`wrote ${OUT} (${files.length} heroes)`);
